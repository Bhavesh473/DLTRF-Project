# ── Human-readable action label ───────────────────────────────────────────────
def _what_user_did(method: str, path: str) -> str:
    p = path.lower()
    m = method.upper()

    if any(x in p for x in ("login", "signin", "sign_in")) and m == "POST":
        return "🔑 Logged in"
    if "logout" in p or "signout" in p:
        return "🚪 Logged out"
    if any(x in p for x in ("register", "signup", "sign_up")) and m == "POST":
        return "📝 Registered"
    if "basket" in p or "cart" in p:
        if any(x in p for x in ("checkout", "purchase", "order/place")) and m == "POST":
            return "💳 Placed order"
        if m == "DELETE":  return "🗑 Removed from cart"
        if m == "POST":    return "🛒 Added to cart"
        return "👀 Loaded cart"
    if "order" in p and m == "POST":        return "📦 Placed order"
    if "checkout" in p and m == "POST":     return "💳 Checked out"
    if "address" in p:
        return "📍 Saved address" if m in ("POST", "PUT") else "👀 Loaded addresses"
    if any(x in p for x in ("card", "payment", "paymentmethod")):
        return "💳 Saved payment" if m in ("POST", "PUT") else "👀 Payment options"
    if "wallet" in p:
        return "💰 Loaded wallet" if m == "GET" else "💰 Updated wallet"
    if "delivery" in p:
        return "🚚 Delivery options"
    if any(x in p for x in ("whoami", "profile", "me", "account")):
        return "👤 Loaded profile"
    if any(x in p for x in ("shelves", "shelf")):
        return "📚 Browsed shelves" if m == "GET" else "📚 Shelf action"
    if any(x in p for x in ("books", "/book/")):
        return "📖 Browsed books" if m == "GET" else "📖 Book action"
    if any(x in p for x in ("pages", "/page/")):
        return "📄 Viewed page" if m == "GET" else "📄 Page action"
    if "webhook" in p:
        return "🔗 Webhook action"
    if "preferences" in p:
        return "⚙️ Changed preference" if m == "POST" else "⚙️ Loaded preferences"
    if "search" in p:
        return "🔍 Searched"
    if any(x in p for x in ("socket.io", "/ws/", "websocket")):
        return "📡 WebSocket (bg)"
    if "admin" in p and m == "GET":
        return "⚙️ Admin (bg)"
    suffix = p.rsplit(".", 1)[-1] if "." in p.split("/")[-1] else ""
    if suffix in ("js", "css", "png", "jpg", "jpeg", "gif", "svg",
                  "woff", "woff2", "ico", "map", "ttf"):
        return "🌐 Static asset (bg)"
    if m == "POST":   return f"📤 POST {path}"
    if m == "PUT":    return f"✏️ PUT {path}"
    if m == "DELETE": return f"🗑 DELETE {path}"
    if m == "PATCH":  return f"✏️ PATCH {path}"
    return f"📥 GET {path}"


# ── Core classification engine ────────────────────────────────────────────────
def _classify_divergence(
    evt: Dict[str, Any],
    config: Dict[str, Any],
) -> Dict[str, str]:
    path          = evt.get("path", "")
    method        = evt.get("method", "GET").upper()
    orig          = str(evt.get("original_status", ""))
    replay        = str(evt.get("replay_status", ""))
    original_tier = evt.get("tier", "INVESTIGATE")

    # 1. Custom rules
    for rule in config.get("custom_rules", []):
        m = rule.get("match", {})
        patterns = m.get("path_patterns", [])
        if patterns and not any(fnmatch.fnmatch(path, p) for p in patterns):
            continue
        methods = [x.upper() for x in m.get("methods", [])]
        if methods and method not in methods:
            continue
        orig_statuses = [str(s) for s in m.get("original_statuses", [])]
        if orig_statuses and orig not in orig_statuses:
            continue
        replay_statuses = [str(s) for s in m.get("replay_statuses", [])]
        if replay_statuses and replay not in replay_statuses:
            continue
        return {
            "tier":           rule.get("tier", original_tier),
            "rule_id":        rule.get("id", "custom"),
            "rule_label":     rule.get("label", "Custom Rule"),
            "reason":         (rule.get("reason") or "").strip(),
            "recommendation": (rule.get("recommendation") or "").strip(),
        }

    # 2. Global noise transitions
    for trans in config.get("global_noise", {}).get("status_transitions", []):
        if str(trans.get("from", "")) == orig and str(trans.get("to", "")) == replay:
            return {
                "tier":           "EXPECTED",
                "rule_id":        f"global_noise:{trans['from']}->{trans['to']}",
                "rule_label":     f"Global Noise: {trans['from']}→{trans['to']}",
                "reason":         (trans.get("reason") or "").strip(),
                "recommendation": (trans.get("recommendation") or "").strip(),
            }

    # 3. Fallback — no rule matched
    return {
        "tier":           original_tier,
        "rule_id":        "no_match",
        "rule_label":     "No Rule Matched",
        "reason":         "",
        "recommendation": "",
    }


def _auth_tag_str(auth_mode: str, auth_active: bool) -> str:
    if auth_mode == "jwt":    return "with JWT 🔑"
    if auth_mode == "cookie": return "with Session 🍪"
    if auth_active:           return "authenticated 🔐"
    return "no auth ⚠"


# ── Build template context ────────────────────────────────────────────────────
def build_ctx(report: Dict[str, Any], config: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    if config is None:
        config = report.get("config", {})

    raw      = report.get("divergences") or {}
    expected = list(raw.get("expected", []))
    invest   = list(raw.get("investigate", []))
    critical = list(raw.get("critical", []))

    if not any([expected, invest, critical]):
        for d in report.get("divergence_analysis", {}).get("details", []):
            t = d.get("tier", "INVESTIGATE")
            if t == "EXPECTED":   expected.append(d)
            elif t == "CRITICAL": critical.append(d)
            else:                 invest.append(d)

    summary  = report.get("summary", {})
    total    = summary.get("total_events", 0)
    duration = summary.get("duration_seconds", 0)
    avg_ms   = report.get("performance", {}).get("avg_response_time_ms", 0)
    rid      = report.get("replay_id", "unknown")
    ts       = report.get("timestamp", "")

    auth_mode   = summary.get("auth_mode", "none")
    auth_active = summary.get("auth_was_active", False)
    if not auth_active and summary.get("jwt_token_injected", False):
        auth_mode   = "jwt"
        auth_active = True

    def reclassify_list(events: list, engine_tier: str) -> Tuple[list, list, list]:
        _exp, _inv, _crit = [], [], []
        for evt in events:
            evt = dict(evt)
            evt["tier"] = engine_tier
            cl = _classify_divergence(evt, config)
            evt.update({
                "tier":                          cl["tier"],
                "rule_id":                       cl["rule_id"],
                "rule_label":                    cl["rule_label"],
                "classification_reason":         cl["reason"],
                "classification_recommendation": cl["recommendation"],
            })
            t = cl["tier"]
            if t == "EXPECTED":   _exp.append(evt)
            elif t == "CRITICAL": _crit.append(evt)
            else:                 _inv.append(evt)
        return _exp, _inv, _crit

    exp_from_exp, inv_from_exp, crit_from_exp = reclassify_list(expected,  "EXPECTED")
    exp_from_inv, inv_from_inv, crit_from_inv = reclassify_list(invest,    "INVESTIGATE")
    exp_from_crt, inv_from_crt, crit_from_crt = reclassify_list(critical,  "CRITICAL")

    expected_final = exp_from_exp + exp_from_inv + exp_from_crt
    invest_final   = inv_from_exp + inv_from_inv + inv_from_crt
    critical_final = crit_from_exp + crit_from_inv + crit_from_crt

    reclassified_lookup = {
        evt.get("event_id", ""): evt
        for evt in expected_final + invest_final + critical_final
    }

    ne, ni, nc = len(expected_final), len(invest_final), len(critical_final)
    n_exact = total - ne - ni - nc
    rate    = round((n_exact + ne) / total * 100, 1) if total > 0 else 100.0

    # ── Verdict logic ─────────────────────────────────────────────────────────
    # nc_unclassified = CRITICAL items with NO matching rule (genuine unknowns)
    # Classified CRITICAL items (rule_id != "no_match") are explained — not genuine bugs
    nc_unclassified = sum(1 for e in critical_final if e.get("rule_id", "") in ("no_match", ""))
    
    if total == 0:
        verdict, vcol, vtext = "INVALID", "#6b7280", "No traffic found to replay."
        rate_col = "#6b7280"
        rate = 0.0
    elif rate >= 95.0 and nc_unclassified == 0:
        verdict, vcol, vtext = "PASS",   "#16a34a", "High Reproducibility. Approved."
        rate_col = "#16a34a"
    elif rate >= 95.0 and nc_unclassified > 0:
        verdict, vcol, vtext = "REVIEW", "#d97706", "Unclassified divergences found. Review before promoting."
        rate_col = "#d97706"
    elif rate >= 80.0:
        verdict, vcol, vtext = "REVIEW", "#d97706", "Acceptable reproducibility. Check divergences."
        rate_col = "#d97706"
    else:
        verdict, vcol, vtext = "FAIL",   "#dc2626", "Low reproducibility. Do not ship."
        rate_col = "#dc2626"

    # ── Final statement ───────────────────────────────────────────────────────
    if total == 0:
        final_stmt = "<strong>0 requests found.</strong> The selected timeframe contains no logs to replay. Please record new traffic."
    elif nc_unclassified == 0 and ni == 0:
        final_stmt = (
            f"<strong>{n_exact} request{'s' if n_exact != 1 else ''} reproduced exactly.</strong> "
            + (f"{ne} divergence{'s' if ne != 1 else ''} classified as expected noise — excluded from repro rate. " if ne > 0 else "")
            + (f"{nc} divergence{'s' if nc != 1 else ''} classified with a known cause and rule. " if nc > 0 else "")
            + "No unclassified mismatches. <strong>Clear to promote.</strong>"
        )
    elif nc_unclassified == 0:
        final_stmt = (
            f"<strong>{rate}% Reproducibility.</strong> "
            f"There are {ni} item{'s' if ni != 1 else ''} that require manual review. "
            "No unclassified mismatches detected. "
            "<strong>Review the investigation tab, then promote.</strong>"
        )
    elif rate >= 95.0:
        final_stmt = (
            f"<strong>{rate}% Reproducibility Achieved.</strong> "
            f"The application is highly deterministic, but {nc_unclassified} divergence{'s have' if nc_unclassified != 1 else ' has'} "
            "no matching rule in <code>divergence_config.yaml</code>. "
            "These may be expected state drift that needs a new rule, or genuine non-determinism. "
            "<strong>Review the Genuine Bugs tab. Add a rule if expected, leave if it is a real bug.</strong>"
        )
    else:
        final_stmt = (
            f"<strong>Only {rate}% Reproducibility.</strong> "
            f"{nc_unclassified} unclassified mismatch{'es' if nc_unclassified != 1 else ''} found. "
            "The application state is highly volatile or real bugs exist. "
            "<strong>Do not ship until resolved.</strong>"
        )

    # ── Investigation panel intro ─────────────────────────────────────────────
    if ni > 0:
        inv_rules  = list(dict.fromkeys(d.get("rule_label", "No Rule Matched") for d in invest_final))
        rules_text = ", ".join(f"<em>{r}</em>" for r in inv_rules[:3])
        if len(inv_rules) > 3:
            rules_text += f", +{len(inv_rules) - 3} more"
        invest_intro = (
            f"<strong>{ni} item{'s' if ni != 1 else ''} to investigate.</strong> "
            f"Matched rule{'s' if len(inv_rules) > 1 else ''}: {rules_text}. "
            "Each card below shows the exact rule that matched and the recommended action."
        )
    else:
        invest_intro = "<strong>Nothing to investigate.</strong> All divergences were classified as expected noise."

    def tag(evt: Dict[str, Any], diverged: bool = False) -> Dict[str, Any]:
        evt = dict(evt)
        o = evt.get("original_status")
        r = evt.get("replay_status")
        tier = evt.get("tier", "")

        evt_auth_mode   = evt.get("auth_mode", auth_mode)
        evt_auth_active = evt.get("auth_was_active", evt.get("jwt_was_active", auth_active))

        ol, oc = _status_info(o)
        rl, rc = _status_info(r)
        if not diverged:
            rc = "#16a34a"

        atag = _auth_tag_str(evt_auth_mode, evt_auth_active)
        if o == r:
            engine_txt = f"Replayed {evt.get('method','')} {evt.get('path','')} ({atag}) → ✅ {r}"
        else:
            engine_txt = f"Replayed {evt.get('method','')} {evt.get('path','')} ({atag}) → ❌ got {r}, expected {o}"

        return {
            **evt,
            "diverged":                      diverged,
            "tier":                          tier,
            "tier_color":                    _TIER_COLORS.get(tier, "#aaa"),
            "method_color":                  _METHOD_COLORS.get(str(evt.get("method", "")).upper(), "#aaa"),
            "o_label": ol, "o_color": oc,
            "r_label": rl, "r_color": rc,
            "user_action":                   _what_user_did(evt.get("method", "GET"), evt.get("path", "/")),
            "engine_action":                 engine_txt,
            "short_id":                      str(evt.get("event_id", ""))[:8],
            "rule_id":                       evt.get("rule_id", ""),
            "rule_label":                    evt.get("rule_label", ""),
            "classification_reason":         evt.get("classification_reason", ""),
            "classification_recommendation": evt.get("classification_recommendation", ""),
        }

    all_evts = report.get("all_events", [])
    session  = []
    if all_evts:
        for e in all_evts:
            eid = e.get("event_id", "")
            if eid in reclassified_lookup:
                session.append(tag(reclassified_lookup[eid], diverged=True))
            else:
                session.append(tag(e, diverged=False))
    else:
        for d in invest_final + critical_final:
            session.append(tag(d, diverged=True))

    if auth_mode == "jwt":
        auth_badge_cls, auth_badge_text = "yes", "✓ JWT"
    elif auth_mode == "cookie":
        auth_badge_cls, auth_badge_text = "yes", "✓ Session Cookie"
    else:
        auth_badge_cls, auth_badge_text = "no", "⚠ no auth"

    auth_notes      = config.get("auth_notes", {})
    mode_note       = auth_notes.get(auth_mode, auth_notes.get("none", {}))
    auth_note_title = mode_note.get("title", "⏱ Auth")
    auth_note_body  = mode_note.get("body", "")

    app_meta = config.get("app", {})
    app_name = app_meta.get("name", "")
    app_desc = app_meta.get("description", "")

    return {
        "rid":              rid,
        "ts":               ts,
        "total":            total,
        "duration":         duration,
        "avg_ms":           avg_ms,
        "auth_mode":        auth_mode,
        "auth_active":      auth_active,
        "auth_badge_cls":   auth_badge_cls,
        "auth_badge_text":  auth_badge_text,
        "auth_note_title":  auth_note_title,
        "auth_note_body":   auth_note_body,
        "app_name":         app_name,
        "app_desc":         app_desc,
        "n_exact":          n_exact,
        "ne":               ne,
        "ni":               ni,
        "nc":               nc,
        "nc_unclassified":  nc_unclassified,
        "rate":             rate,
        "rate_col":         rate_col,
        "verdict":          verdict,
        "vcol":             vcol,
        "vtext":            vtext,
        "final_stmt":       final_stmt,
        "invest_intro":     invest_intro,
        "session":          session,
        "nsession":         len(session),
        "tab_expected":     [tag(d, diverged=True) for d in expected_final],
        "tab_invest":       [tag(d, diverged=True) for d in invest_final],
        "tab_critical":     [tag(d, diverged=True) for d in critical_final],
    }


