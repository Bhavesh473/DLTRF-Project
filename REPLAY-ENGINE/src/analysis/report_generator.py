"""
REPLAY-ENGINE/analysis/report_generator.py
DLTRF report generator — builds the HTML report from replay output.

ARCHITECTURE:
  This module contains ZERO app-specific logic. All classification rules,
  text strings, and app-specific knowledge live in divergence_config.yaml.
  This file is a pure renderer: it evaluates rules and renders HTML.

CLASSIFICATION PIPELINE (in order of precedence):
  1. custom_rules (top-to-bottom, first match wins)
  2. global_noise.status_transitions
  3. Engine's original tier (INVESTIGATE / CRITICAL) — no match fallback

VERDICT LOGIC:
  - PASS   : rate >= 95% AND nc_unclassified == 0
             (classified CRITICAL items with known rules do NOT trigger FAIL)
  - REVIEW : rate >= 95% but nc_unclassified > 0, OR rate 80-94%
  - FAIL   : rate < 80%

  nc_unclassified = items in critical_final where rule_id == "no_match"
  nc              = total critical items (shown in UI tabs, includes classified ones)

To add a new rule for your app: edit divergence_config.yaml.
Do not edit this file for app-specific behaviour.
"""

